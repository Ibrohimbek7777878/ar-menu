@register.simple_tag(takes_context=True)
def t(context, key):
    """Tarjima olish: {{ t.greeting }}"""
    lang = context.get('language', 'uz')
    translations = TRANSLATIONS.get(lang, TRANSLATIONS['uz'])
    return translations.get(key, key)


@register.simple_tag(takes_context=True)
def get_language(context):
    """Joriy tilni olish: {% get_language as lang %}"""
    return context.get('language', 'uz')


@register.simple_tag(takes_context=True)
def lang_url(context, lang_code):
    """Joriy URL ni saqlab, faqat lang ni almashtirish: {% lang_url 'ru' %}"""
    request = context.get('request')
    if not request:
        return f"?lang={lang_code}"
    params = request.GET.copy()
    params['lang'] = lang_code
    qs = params.urlencode()
    return f"?{qs}" if qs else f"?lang={lang_code}"


@register.inclusion_tag('components/language_switcher.html', takes_context=True)
def language_switcher(context):
    """Til almashtirgich — joriy GET ni saqlaydi."""
    request = context.get('request')
    return {
        'current_language': context.get('language', 'uz'),
        'languages': [
            ('uz', "O'zbek"),
            ('ru', 'Русский'),
            ('en', 'English'),
        ],
        'request': request,
    }


